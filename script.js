function normalizeTranslationText(value) {
    return String(value || "")
        .replace(/\s+/g, " ")
        .trim();
}

const translatableTextNodes = [];
const translatableAttributes = [];

function collectTranslations() {
    const walker = document.createTreeWalker(
        document.body,
        NodeFilter.SHOW_TEXT
    );

    let node;

    while ((node = walker.nextNode())) {
        const normalized =
            normalizeTranslationText(node.nodeValue);

        if (!normalized || !translations[normalized]) {
            continue;
        }

        translatableTextNodes.push({
            node,
            uk: node.nodeValue,
            en: translations[normalized]
        });
    }

    document
        .querySelectorAll("[alt], [aria-label], meta[name='description']")
        .forEach((element) => {
            ["alt", "aria-label", "content"].forEach((attribute) => {
                if (!element.hasAttribute(attribute)) {
                    return;
                }

                const original =
                    element.getAttribute(attribute);

                const normalized =
                    normalizeTranslationText(original);

                if (!translations[normalized]) {
                    return;
                }

                translatableAttributes.push({
                    element,
                    attribute,
                    uk: original,
                    en: translations[normalized]
                });
            });
        });
}

function getCurrentLanguage() {
    return (
        localStorage.getItem("portfolioLanguage") === "en"
            ? "en"
            : "uk"
    );
}

function updateLanguageButtons(language) {
    document
        .querySelectorAll(".language-button")
        .forEach((button) => {
            const isActive =
                button.dataset.language === language;

            button.classList.toggle(
                "active",
                isActive
            );

            button.setAttribute(
                "aria-pressed",
                String(isActive)
            );
        });
}

function applyLanguage(language) {
    const safeLanguage =
        language === "en"
            ? "en"
            : "uk";

    document.documentElement.lang =
        safeLanguage;

    translatableTextNodes.forEach((item) => {
        item.node.nodeValue =
            safeLanguage === "en"
                ? item.en
                : item.uk;
    });

    translatableAttributes.forEach((item) => {
        item.element.setAttribute(
            item.attribute,
            safeLanguage === "en"
                ? item.en
                : item.uk
        );
    });

    localStorage.setItem(
        "portfolioLanguage",
        safeLanguage
    );

    updateLanguageButtons(
        safeLanguage
    );

    updateMenuAccessibility();
}

function updateMenuAccessibility() {
    const menuButton =
        document.querySelector(".menu-button");

    const mainNav =
        document.querySelector(".main-nav");

    if (!menuButton || !mainNav) {
        return;
    }

    const language =
        getCurrentLanguage();

    const isOpen =
        mainNav.classList.contains(
            "mobile-open"
        );

    menuButton.setAttribute(
        "aria-label",
        language === "en"
            ? (
                isOpen
                    ? "Close Menu"
                    : "Open Menu"
            )
            : (
                isOpen
                    ? "Закрити меню"
                    : "Відкрити меню"
            )
    );
}

